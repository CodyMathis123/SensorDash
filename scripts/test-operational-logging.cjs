const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = (file) => fs.readFileSync(file, 'utf8');

const logging = read('src/SensorDash/OperationalLogging.cs');
const collector = read('src/SensorDash/Program.cs');
const exporter = read('src/SensorDash/TelemetryExport.cs');
const notifications = read('src/SensorDash/WindowsPowerResumeNotifications.cs');
const installer = read('installer/SensorDash.wxs');
const upgrade = read('scripts/Test-MsiUpgrade.ps1');

assert.match(installer, /util:EventSource[^>]+Name="SensorDash\.Collector"[^>]+Log="SensorDash"/);
assert.match(installer, /ComponentRef Id="SensorDashOperationalEventSource"/);
assert.match(logging, /LogName = "SensorDash"/);
assert.match(logging, /SourceName = "SensorDash\.Collector"/);
assert.match(logging, /logging\.ClearProviders\(\)/);
assert.match(logging, /logging\.AddEventLog/);
assert.match(logging, /level >= LogLevel\.Warning/);
assert.match(logging, /level >= LogLevel\.Information/);
assert.match(collector, /OperationalEvents\.Configure\(builder\.Logging\)/);
assert.match(collector, /OperationalEvents\.CollectorStarted/);
assert.match(collector, /OperationalEvents\.CollectorStopping/);
assert.match(collector, /OperationalEvents\.ResumeReopenStarted/);
assert.match(collector, /OperationalEvents\.ResumeReopenCompleted/);
assert.match(collector, /_collectionOutage\.Failed/);
assert.match(collector, /_collectionOutage\.Recovered/);
assert.match(exporter, /_initializationOutage\.Failed\(exception, initializationStage\)/);
assert.match(exporter, /_initializationOutage\.Recovered\(\)/);
assert.match(exporter, /_deliveryOutage\.Failed\(e, deliveryStage\)/);
assert.match(exporter, /deliveredThisIteration/);
assert.match(exporter, /_deliveryOutage\.Recovered\(\)/);
assert.match(exporter, /_catalogOutage\.Failed\(e, "catalog-sync"\)/);
assert.match(exporter, /_catalogOutage\.Recovered\(\)/);
assert.doesNotMatch(exporter, /logger\.LogWarning\("Telemetry (delivery failed|catalog synchronization failed|exporter could not initialize)/);
assert.match(notifications, /OperationalEvents\.ResumeRegistrationFailure/);
assert.match(upgrade, /Get-WinEvent -ListLog 'SensorDash'/);
assert.match(upgrade, /Get-WinEvent -FilterHashtable/);
assert.match(logging, /OperationalLoggingSelfTest/);
assert.match(collector, /OperationalLoggingSelfTest\.Run\(\)/);
console.log('PASS: dedicated log registration, noise filters, event ids and outage transitions are wired.');
