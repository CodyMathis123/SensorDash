'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const {readCatalog,validatePreset}=require('./validate-cooling-presets.cjs');
const items=readCatalog(),fan=items.find(p=>p.kind==='fan-group');
const invalid=change=>{const x=structuredClone(fan);change(x);assert.throws(()=>validatePreset(x));};
invalid(x=>x.schemaVersion=2);invalid(x=>x.revision=0);invalid(x=>x.kind='other');
invalid(x=>x.electrical.quantity=19);invalid(x=>x.electrical.rpmSensorId='hardware');
invalid(x=>x.electrical.lowDutyPercent=10);invalid(x=>x.electrical.volts=-1);
invalid(x=>x.sources=[]);invalid(x=>x.sources[0].url='javascript:alert(1)');
invalid(x=>x.electrical.powerCurve[0].watts=-1);
invalid(x=>x.electrical.powerCurve[0].rpm=483);
invalid(x=>x.electrical.powerCurve=[{watts:1},{watts:2}]);
invalid(x=>delete x.electrical.powerCurveSource);
const code=fs.readFileSync('src/SensorDash/wwwroot/cooling-electrical.js','utf8');
const api=vm.runInNewContext(code+'\nCoolingElectrical;');
assert.match(api.presetPicker({kind:'pump'},'x'),/Presets unavailable/);
api.setCatalog(items);
const c={id:'c',kind:'fan-group',sensorIds:['tach'],electrical:{quantity:7,volts:5,wattsPerUnit:99,rpmSensorId:'tach',powerSource:'My hub',sourceMaxAmps:4,measuredLowWatts:3,measuredHighWatts:10,lowDutyPercent:20,highDutyPercent:80}};
const S={settings:{coolingSystems:[{id:'s',components:[c]}]}};
assert.equal(api.applyPreset(S,'component:s:c',fan.id),true);
assert.equal(c.electrical.quantity,7);assert.equal(c.electrical.rpmSensorId,'tach');
assert.equal(c.electrical.powerSource,'My hub');assert.equal(c.electrical.sourceMaxAmps,4);
assert.equal(c.electrical.measuredLowWatts,3);assert.equal(c.electrical.wattsPerUnit,null);
assert.equal(c.electrical.presetRevision,1);assert.equal(c.electrical.presetId,fan.id);
const snapshot=JSON.stringify(c.electrical);
const newer=structuredClone(items);newer.find(p=>p.id===fan.id).electrical.volts=6;
api.setCatalog(newer);assert.equal(JSON.stringify(c.electrical),snapshot,'Catalog update must not modify saved snapshots');
const additional={...structuredClone(fan),id:'another-fan',model:'Another fan'};
api.setCatalog([...items,additional]);assert.match(api.presetPicker(c,'component:s:c'),/Another fan/);
assert.doesNotMatch(api.presetPicker({kind:'pump'},'x'),/Another fan/);
assert.equal(api.applyPreset(S,'component:s:c',additional.id),true,'A JSON-only addition is selectable and applicable');
assert.equal(api.applyPreset(S,'component:s:c',items.find(p=>p.kind==='pump').id),false);
console.log('PASS: catalog schema, provenance, scope, quantity/mapping preservation, snapshots and JSON-only extensions');
